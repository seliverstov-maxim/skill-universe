#!/bin/sh
# Keep pipe-compatible installers in sync with the shared defaults and body.
set -eu
root=$(CDPATH='' cd "$(dirname "$0")/.." && pwd)
cd "$root"
case "${1-}" in ''|--check) ;; *) printf 'Usage: %s [--check]\n' "$0" >&2; exit 1 ;; esac
generated=$(mktemp)
trap 'rm -f -- "$generated"' 0
{
    printf '#!/bin/sh\n# shellcheck disable=SC2034 # Some embedded defaults are CLI-only.\nset -eu\n# Generated by scripts/generate-installer.sh; edit env.sh and scripts/install-body.sh.\n'
    cat env.sh scripts/install-body.sh
} > "$generated"
for destination in install.sh docs/install.sh; do
    if [ "${1-}" = --check ]; then
        cmp "$generated" "$destination" || { printf 'Regenerate installers.\n' >&2; exit 1; }
    else
        cat "$generated" > "$destination"
    fi
done
